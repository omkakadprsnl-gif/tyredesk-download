import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import 'fake-indexeddb/auto';
import {calculateBill} from '../docs/app/src/logic.mjs';
import {all,completeOrder,put,exportBackup,receivedDraft,restoreBackup,saveReceivedDraft,saveSetting} from '../docs/app/src/db.mjs';
const line=(unitPaise,taxBps=1800)=>({qty:1,unitPaise,taxBps,name:'Audit item'});
const tiny=calculateBill([line(1),line(1),line(0)],{type:'fixed',value:1},{registered:true});
assert.deepEqual(tiny.lines.map(l=>l.taxablePaise),[0,1,0]);
assert.equal(tiny.totals.grandPaise,1);
const receipt=calculateBill([line(100000),line(20000)],{type:'fixed',value:12000},{registered:true,supplyMode:'intra'});
assert.equal(receipt.totals.taxablePaise,108000);
assert.equal(receipt.totals.taxPaise,19440);
assert.equal(receipt.totals.grandPaise,127440);
assert.equal(receipt.totals.cgstPaise+receipt.totals.sgstPaise,19440);
assert.throws(()=>calculateBill([{...line(100),qty:1.5}]),/quantity/i);
await saveSetting({name:'Audit shop',gstRegistered:false,createdAt:'2026-11-22'});
await saveReceivedDraft({requestId:'audit-draft',draftReceipts:[{id:'audit-payment',amountPaise:1500}]});
await completeOrder({requestId:'audit-invoice',customerName:'Test',items:[line(2000)],paidPaise:1500});
const json=await exportBackup();
await restoreBackup(json);
assert.equal((await receivedDraft()).draftReceipts[0].amountPaise,1500);
assert.equal((await all('payments')).length,1);
const duplicate=JSON.parse(json);
duplicate.payload.data.orders.push(duplicate.payload.data.orders[0]);
duplicate.checksum=createHash('sha256').update(JSON.stringify(duplicate.payload)).digest('hex');
await assert.rejects(restoreBackup(JSON.stringify(duplicate)),/duplicate/);
assert.equal((await all('orders')).length,1);
await assert.rejects(restoreBackup(json.replace('Audit shop','Corrupted')),/checksum/i);
await put('meta',{id:'invoice-'+new Date().getFullYear(),value:0});
const next=await completeOrder({requestId:'audit-next',customerName:'Test',items:[line(100)]});
assert.notEqual(next.number,(await all('orders')).find(o=>o.requestId==='audit-invoice').number);
console.log('PASS: independently reconciled paise, GST, no negative taxable line, and backup of confirmed draft receipts');

