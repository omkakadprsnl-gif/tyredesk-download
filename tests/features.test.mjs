import assert from 'node:assert/strict';
import 'fake-indexeddb/auto';
import {consentRecord,LEGAL_VERSION} from '../docs/app/src/legal.mjs';
import {saveSetting,getSetting,completeOrder,addPayment,all,summaryData,exportBackup,restoreBackup,addCatalogItem,recordPurchase} from '../docs/app/src/db.mjs';
assert.throws(()=>consentRecord(false));
const consent=consentRecord(true);assert.equal(consent.termsVersion,LEGAL_VERSION);assert.ok(Date.parse(consent.acceptedAt));
await saveSetting({name:'Test Shop',legalConsent:consent,paymentQrData:'data:image/png;base64,test'});
const order=await completeOrder({requestId:'test-bill',customerName:'Customer',items:[{name:'Alignment',type:'service',qty:1,unitPaise:100000,taxBps:0}],paidPaise:0});
assert.equal((await all('payments')).length,0,'Completing unpaid bill must not record payment');
const attempts=await Promise.all([addPayment(order.id,30000,'upi','','same-confirmation'),addPayment(order.id,30000,'upi','','same-confirmation')]);
assert.equal(attempts[0].id,attempts[1].id);assert.equal((await all('payments')).length,1,'Repeated partial payment confirmation must be idempotent');
assert.equal((await summaryData()).orders[0].duePaise,70000);
await addPayment(order.id,10000,'upi','UPI-123','reference-test');
await assert.rejects(addPayment(order.id,10000,'upi','upi-123','different-token'),/already been recorded/);
await assert.rejects(addPayment(order.id,80000,'upi','','overpay'));
const concurrent=await Promise.allSettled([addPayment(order.id,60000,'upi','','final1'),addPayment(order.id,60000,'upi','','final2')]);
assert.equal(concurrent.filter(x=>x.status==='fulfilled').length,1,'Concurrent confirmations cannot overpay');
assert.equal((await summaryData()).orders[0].duePaise,0);
const tyre=await addCatalogItem({name:'MRF 185/65 R15',type:'tyre',pricePaise:500000,openingStockQty:2});
await recordPurchase({productId:tyre.id,qty:4,costPaise:300000,supplier:'Supplier',reference:'S-1'});
assert.equal((await all('catalog')).find(p=>p.id===tyre.id).stockQty,6);
const backup=await exportBackup();await restoreBackup(backup);
assert.deepEqual((await getSetting()).legalConsent,consent);
assert.equal((await getSetting()).paymentQrData,'data:image/png;base64,test');
assert.equal((await all('purchases')).length,1);assert.equal((await all('payments')).length,3);
console.log('PASS: consent, payment confirmations, manual stock purchase and backup restore');

const service=(await all('catalog')).find(p=>p.type==='service');
assert.equal(service.name,'Alignment');assert.equal(service.pricePaise,100000);
await completeOrder({customerName:'Another customer',items:[{name:'  ALIGNMENT  ',type:'service',qty:1,unitPaise:80000}]});
assert.equal((await all('catalog')).filter(p=>p.type==='service').length,1);
assert.equal((await all('catalog')).find(p=>p.id===service.id).pricePaise,100000);
